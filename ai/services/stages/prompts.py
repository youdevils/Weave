    "the evidence `segments` say, as explicit claims with verbatim provenance. You do not decide model changes "
    "and you do not see existing model data; OnyxJar maps your claims onto the model afterwards. Never bend a "
    "statement to fit the catalogue.\n\n"
    "SEGMENTS: the evidence arrives as segments, each with source_id, segment_id, kind, its literal text, and "
    "`within`: the segment_ids of the headings (and, for a table row, the table) it sits under. Those heading and "
    "table segments are included too -- a table segment's text is its header row. Headings and headers are not "
    "themselves claims about the domain, but layout can convey a relationship (support='structural', below).\n\n"
    "INTENT FRAME (only when frame_intent is true; otherwise return it empty):\n"
    "- targets: each kind of thing the intent asks to add/update/retire/link. type_label = the intent's own "
    "word for the kind; type_hint = a catalogue key only if it obviously fits; excerpt = a verbatim span of the "
    "intent that names it -- never elided with '...'. Several targets may quote the same span (\"add the Xs "
    "and Ys\" frames 'Xs' and 'Ys', both quoting it). A request for relationships in general is "
    "include_related, not a target.\n"
    "- anchors: existing entities the intent names, each with a verbatim excerpt.\n"
    "- include_related: true only if the intent asks for associated relationships too; quote those words in "
    "include_related_excerpt.\n"
    "- restated_intent: one sentence.\n\n"
    "EVIDENCE: go through EVERY segment. Tables and lists are evidence too: one row can state several things "
    "at once (a row 'Entity A | Entity B | Entity C' under a header 'Type X | Type Y | Type Z' names three "
