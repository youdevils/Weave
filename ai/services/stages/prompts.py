    "listed against it, over every row of the table), prose claims and adjudicated answers. Check each against its "
    "basis and the `segments`.\n"
    "Q2 -- are the decisions that PREVENTED other changes justified? `causes_of_blocks` lists every blocked item with "
    "its state -- undecidable (meaning could not be decided), insufficient_evidence (evidence exists but does not "
